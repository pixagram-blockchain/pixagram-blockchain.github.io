#!/usr/bin/env node
/**
 * scripts/i18n-home.js — builds src/js/locales/home.js.
 *
 * home.js is the one translation file that ships inside the main bundle. It
 * holds the strings the landing page (and the shell around it) paints first,
 * in EVERY language — a few hundred bytes per language. utils/text.js answers
 * from it while the visitor's full language file (locales/<lang>.js, 80–100 kB
 * gzipped, its own chunk) is still downloading, so the homepage shows its
 * text on the first frame instead of waiting for that chunk.
 *
 * The per-language files stay the single source of truth: every string in
 * home.js is copied from them by this script, so home.js is never edited by
 * hand. It runs before every `npm run dev` / `npm run build` (predev /
 * prebuild), so a change to locales/<lang>.js reaches home.js automatically.
 *
 *   node scripts/i18n-home.js           write home.js
 *   node scripts/i18n-home.js --check   exit 1 if home.js is out of date
 *
 * To put a string on the first frame, add its key (or a "prefix." for a whole
 * namespace) to KEYS below. Keep it to what renders before any interaction:
 * everything else is read from the full file, which lands a moment later.
 */
"use strict";

const fs = require("fs");
const path = require("path");
const vm = require("vm");

const DIR = path.join(__dirname, "..", "src", "js", "locales");
const OUT = path.join(DIR, "home.js");

const KEYS = [
    // The landing page (pages/Home.js) — the whole namespace.
    "components.home.",
    // The shell around it on first paint (search field of the top bar).
    "words.search",
];

/** Files in locales/ that are not a language. */
const NOT_A_LANGUAGE = new Set(["home.js", "svg.js"]);

const load = (file) => {
    const src = fs.readFileSync(path.join(DIR, file), "utf8").replace(/export\s+default\s+/, "module.exports = ");
    const ctx = { module: { exports: {} } };
    vm.runInNewContext(src, ctx, { filename: file });
    return ctx.module.exports;
};

const flatten = (node, prefix, out) => {
    for (const key of Object.keys(node)) {
        const p = prefix ? prefix + "." + key : key;
        const v = node[key];
        if (v && typeof v === "object" && !Array.isArray(v)) flatten(v, p, out);
        else out.set(p, v);
    }
    return out;
};

const wanted = (key) => KEYS.some((k) => (k.endsWith(".") ? key.startsWith(k) : key === k));

const files = fs.readdirSync(DIR)
    .filter((f) => /^[a-z]{2,3}(_[a-z]{2,8})?\.js$/.test(f) && !NOT_A_LANGUAGE.has(f))
    .sort((a, b) => (a === "en.js" ? -1 : b === "en.js" ? 1 : a.localeCompare(b)));

const en = flatten(load("en.js"), "", new Map());
const keys = [...en.keys()].filter(wanted);

// Plural and SVG tokens resolve against the full catalogue, which is exactly
// what is not there yet when home.js answers. Refuse them rather than ship a
// homepage that renders "{{{_plurals.x}}}".
for (const k of keys) {
    const v = en.get(k);
    if (typeof v !== "string") throw new Error(`${k}: home.js holds plain strings only`);
    if (/\{\{\{|%n/.test(v)) throw new Error(`${k}: plural / SVG tokens cannot be answered from home.js`);
}
for (const k of KEYS) {
    if (!k.endsWith(".") && !en.has(k)) throw new Error(`${k}: not in locales/en.js`);
}

const blocks = [];
let bytes = 0;
for (const file of files) {
    const code = file.replace(/\.js$/, "");
    const flat = code === "en" ? en : flatten(load(file), "", new Map());
    const lines = [];
    for (const k of keys) {
        const v = flat.get(k);
        // A language that lacks a key simply omits it: text.js falls back to
        // the "en" block here, as it does to en.js later.
        if (typeof v === "string") lines.push(`        ${JSON.stringify(k)}: ${JSON.stringify(v)}`);
    }
    const block = `    ${JSON.stringify(code)}: {\n${lines.join(",\n")}\n    }`;
    bytes += Buffer.byteLength(block);
    blocks.push(block);
}

const out = `/**
 * locales/home.js — GENERATED by scripts/i18n-home.js. Do not edit by hand:
 * change locales/<lang>.js, then run \`npm run i18n:home\` (dev and build run
 * it for you).
 *
 * The strings the landing page paints first, in every language. Bundled with
 * the app so the homepage has its text on the first frame; utils/text.js
 * answers from here only until the full language file has loaded.
 */

export default {
${blocks.join(",\n")}
};
`;

if (process.argv.includes("--check")) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    if (current !== out) {
        console.error("locales/home.js is out of date — run `npm run i18n:home`.");
        process.exit(1);
    }
    console.log("locales/home.js is up to date.");
} else {
    fs.writeFileSync(OUT, out);
    console.log(`locales/home.js: ${keys.length} keys × ${files.length} languages, ${(bytes / 1024).toFixed(1)} kB`);
}
